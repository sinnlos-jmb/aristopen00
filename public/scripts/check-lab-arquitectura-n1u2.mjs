import assert from 'node:assert/strict';
import fs from 'node:fs';
import { construirModeloArquitectura, obtenerContexto, elementosArquitectura } from '../js/lab/architectureModel.js';

const lectura = JSON.parse(fs.readFileSync(new URL('./fixtures/n1u2-unidades.json', import.meta.url), 'utf8'));
const propuesta = JSON.parse(fs.readFileSync(new URL('../lab/n1u1-propuestas-libro-i.json', import.meta.url), 'utf8'));
const model = construirModeloArquitectura(lectura, propuesta);
assert.equal(model.stats.macrounidades, 4);
assert.equal(model.stats.unidades, 13);
assert.equal(model.stats.subunidades, 175);
assert.equal(model.stats.momentosRegistrados, 52);
assert.equal(model.stats.momentosPropuestos, 14);
assert.equal(model.macros[0].unidades.map(u => u.id).join(','), 'proemio,metodo,felicidad_opiniones,modos_vida');
assert.match(propuesta.macrounidades_propuestas[1].resultado, /virtud completa en una vida entera/);
const initial = { macroId: null, unidadId: null, momentoId: null, subId: null };
const root = elementosArquitectura(model, initial);
assert.equal(root.filter(x => x.group === 'nodes').length, 4);
assert.equal(root.filter(x => x.group === 'edges').length, 3);
assert(root.filter(x => x.group === 'edges').every(x => x.data.tipo === 'orden_textual'));
const macro = { ...initial, macroId: 'macro:I-V' };
assert.equal(elementosArquitectura(model, macro).filter(x => x.data.tipo === 'unidad').length, 4);
const unit = { ...macro, unidadId: 'proemio' };
assert.equal(obtenerContexto(model, unit).momentos.length, 4);
const moment = { ...unit, momentoId: 'n1u:proemio:I' };
const elements = elementosArquitectura(model, moment);
assert.equal(elements.filter(x => x.data.tipo === 'subunidad').length, 3);
assert(elements.filter(x => x.group === 'edges').every(x => ['orden_textual','contiene','articula'].includes(x.data.tipo)));
const registered = { ...initial, macroId: 'macro:VI-VII', unidadId: 'idea_bien' };
assert.equal(obtenerContexto(model, registered).momentos[0].origen, 'registrado');
assert.throws(() => construirModeloArquitectura({ revision: 'otra', tags: lectura.tags }, propuesta), /otra revisión/);
const invalid = structuredClone(propuesta);
invalid.momentos_propuestos_I_V[0].sub_ids.push('no-existe');
assert.throws(() => construirModeloArquitectura(lectura, invalid), /subunidad ajena/);
const duplicated = structuredClone(propuesta);
duplicated.macrounidades_propuestas[1].unit_ids.push('proemio');
assert.throws(() => construirModeloArquitectura(lectura, duplicated), /más de una macrounidad/);
console.log('N1-U.2 OK: 4 macrounidades, 13 unidades, 175 subunidades, 52 momentos registrados, 14 propuestos; navegación y validaciones.');
