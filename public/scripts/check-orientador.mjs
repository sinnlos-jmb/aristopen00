import assert from 'node:assert/strict';
import { iniciarOrientacion, siguientePregunta, responderOrientacion, cerrarOrientacion, resumenOrientacion } from '../js/lab/orientador.js';

assert.throws(() => iniciarOrientacion('  '), /inquietud/);
const original = iniciarOrientacion('Quiero entender la naturaleza');
assert.equal(original.consulta.tema, 'phusis');
assert.equal(original.consulta.intencion, null);
assert.equal(siguientePregunta(original).clave, 'intencion');
assert.equal(original.candidatos.length, 0);
assert.equal(original.bitacora.length, 1);
assert.throws(() => responderOrientacion(original, 'arbitrario'), /válida/);
const v1 = responderOrientacion(original, 'relacionar');
assert.equal(original.consulta.intencion, null, 'No mutar sesión anterior');
assert.equal(siguientePregunta(v1).clave, 'destino');
assert.ok(!siguientePregunta(v1).opciones.some(o => o.valor === 'phusis'));
const v2 = responderOrientacion(v1, 'eudaimonia');
const v3 = responderOrientacion(v2, 'principiante');
const v4 = responderOrientacion(v3, 'extensa');
const v5 = responderOrientacion(v4, 'phusis');
assert.equal(siguientePregunta(v5), null);
assert.deepEqual([v5.consulta.tema, v5.consulta.destino, v5.consulta.nivel, v5.consulta.extension, v5.consulta.origen], ['phusis','eudaimonia','principiante','extensa','phusis']);
assert.equal(v5.bitacora.length, 6);
assert.equal(v5.evaluacion, 'no_disponible_v1');
assert.equal(resumenOrientacion(v5).siguiente, null);
const conformidad = cerrarOrientacion(v5, 'conforme');
assert.equal(conformidad.estado, 'conforme');
assert.equal(conformidad.bitacora.at(-1).datos.completa, true);
assert.throws(() => responderOrientacion(conformidad, 'breve'), /terminó/);
const abandono = cerrarOrientacion(v2, 'abandonado');
assert.equal(abandono.bitacora.at(-1).datos.completa, false);
assert.equal(abandono.estado, 'abandonado');
assert.equal(original.bitacora.length, 1);
const sinConcepto = iniciarOrientacion('Quiero comprender algo');
assert.equal(siguientePregunta(sinConcepto).clave, 'tema');
assert.equal(sinConcepto.consulta.tema, null);
const sinPreferencia = responderOrientacion(responderOrientacion(responderOrientacion(sinConcepto,'arete'),'definir'), 'sin_preferencia');
assert.equal(sinPreferencia.consulta.nivel, 'sin_preferencia');
assert.equal(sinPreferencia.consulta.extension, null);
assert.deepEqual(JSON.parse(JSON.stringify(conformidad)).consulta, conformidad.consulta);
console.log('OK: orientador V1, aclaraciones, trazabilidad, estados terminales e inmutabilidad.');
