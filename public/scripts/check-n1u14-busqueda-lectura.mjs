// N1-U.14 · Comprobaciones sin MariaDB ni navegador.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { construirIndiceFichas, buscarFichasVectorial, cargarIndiceFichas, tokens } from '../js/lab/architectureSparseSearch.js';
import { normalizarTamanoLector, obtenerTamanoLector, guardarTamanoLector } from '../js/reader/fontPreferences.js';
import { renderChapter } from '../js/reader/render.js';
const base=resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read=(name)=>readFileSync(resolve(base,name),'utf8');
const a=JSON.parse(read('lab/n1u5-fichas-explicativas.json'));
const b=JSON.parse(read('lab/n1u7-fichas-red-piloto.json'));
const index=construirIndiceFichas([...a.fichas,...b.fichas]);
assert.equal(index.docs.length,7);
assert.equal(new Set(index.docs.map(d=>d.id)).size,7);
assert.equal(buscarFichasVectorial(index,'¿Qué es la felicidad?')[0].id,'faq.lab.felicidad');
assert.equal(buscarFichasVectorial(index,'partes del alma')[0].id,'faq.lab.alma');
assert.deepEqual(buscarFichasVectorial(index,'zzzzz qqqqqq'),[]);
assert(!tokens('la de el para por').length);
assert.throws(()=>construirIndiceFichas([a.fichas[0],a.fichas[0]]),/repetida/);
const original=JSON.stringify(a.fichas[0]);
buscarFichasVectorial(index,'política');
assert.equal(JSON.stringify(a.fichas[0]),original,'búsqueda no altera documentos');
const mock={data:new Map([['agora.lab.arquitectura.lectura.v1',JSON.stringify({readerFont:20,graphFont:24,showEdgeNames:false})]]),getItem(k){return this.data.get(k)||null;},setItem(k,v){this.data.set(k,v);}};
assert.equal(obtenerTamanoLector(mock),20);
guardarTamanoLector(22,mock);
assert.deepEqual(JSON.parse(mock.getItem('agora.lab.arquitectura.lectura.v1')),{readerFont:22,graphFont:24,showEdgeNames:false});
assert.equal(normalizarTamanoLector(100),18);
const html=renderChapter({paragraphs:[{number:1,es:'La vida entera.',gr:'Ὅλος βίος.'}]});
assert(html.includes('lang="es"')&&html.includes('lang="el"'));
const css=read('css/reader-n1u14.css');
assert(css.includes('1.7fr')&&css.includes('text-align:justify')&&css.includes('max-width:750px'));
const main=read('js/views/fichas.js');
assert(main.includes('buscarFichasVectorial')&&main.includes('/labo/#/buscar'));
assert(read('js/views/reading.js').includes('controlesTamanoLector'));
assert(read('js/reader/modal.js').includes('controlesTamanoLector'));
assert(read('index.html').includes('/css/reader-n1u14.css'));
// La carga real emplea las fuentes editoriales de la app y no material externo.
const loader=await cargarIndiceFichas(async(path)=>({ok:true,json:async()=>JSON.parse(read(path.replace(/^\//,'')))}));
assert.equal(loader.docs.length,7);
console.log('N1-U.14 OK: 7 fichas, vectores TF-IDF, resultados, corpus inmutable, lector bilingüe y preferencias.');
