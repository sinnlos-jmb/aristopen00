import assert from 'node:assert/strict';
import fs from 'node:fs';
import { construirModeloArquitectura } from '../js/lab/architectureModel.js';
import { construirRelacionesProemio } from '../js/lab/architectureRelations.js';
import { construirCapasProemio } from '../js/lab/architectureLayers.js';
import { construirFichasArquitectura, elementosFichaFAQ, fichaIntroHtml, inspectorFichaFAQHtml } from '../js/lab/architectureCards.js';
import { construirPuentesExplicativos, elementosPuentes, inspectorPuentesHtml } from '../js/lab/architectureBridges.js';
import { construirAmpliacionFichas, elementosRedFichas, inspectorRedFichasHtml } from '../js/lab/architecturePilotNetwork.js';
const read = p => JSON.parse(fs.readFileSync(new URL(p, import.meta.url),'utf8'));
const fuente = read('./fixtures/n1u2-unidades.json');
const original = JSON.stringify(fuente);
const model = construirModeloArquitectura(fuente, read('../lab/n1u1-propuestas-libro-i.json'));
const rels = construirRelacionesProemio(model,read('../lab/n1u3-relaciones-proemio.json'));
const capas = construirCapasProemio(model,rels,read('../lab/n1u4-modulos-proemio.json'));
const fichasBase = construirFichasArquitectura(model,capas,read('../lab/n1u5-fichas-explicativas.json'));
const puentesBase = construirPuentesExplicativos(model,fichasBase,read('../lab/n1u6-puentes-explicativos.json'));
const resource = read('../lab/n1u7-fichas-red-piloto.json');
const {fichas,puentes,red} = construirAmpliacionFichas(model,fichasBase,puentesBase,resource);
assert.equal(fichas.fichas.length,7); assert.equal(puentes.porFicha.size,7);
assert.equal(red.relaciones.length,8); assert.equal(red.porId.size,8);
const drafts=fichas.fichas.filter(f=>f.fuente_editorial?.origen==='propuesta_lab');
assert.equal(drafts.length,4);
for(const f of drafts){
 assert.equal(f.fuente_editorial.trayecto_id,null);
 assert.equal(f.fuente_editorial.estado,'borrador_no_publicado');
 assert.equal(f.pasos.length,6); assert.equal(f.transiciones.length,5);
 assert.deepEqual(f.pasos.map(x=>x.sub_id),puentes.porFicha.get(f.id).apoyos.map(x=>x.sub_id));
 const parts=elementosFichaFAQ(f,model);
 assert.equal(parts.filter(e=>e.group==='nodes').length,6);
 assert.equal(parts.filter(e=>e.group==='edges').length,5);
 assert(parts.filter(e=>e.group==='nodes').every(e=>e.data.label.includes('\n')));
 const intro=fichaIntroHtml(f);
 assert(intro.includes('borrador para curaduría'));
 assert(!inspectorFichaFAQHtml(f,model,null,null).includes('trayecto <code>null</code>'));
 assert(inspectorFichaFAQHtml(f,model,'p1',null).includes('data-arch-read'));
 assert(inspectorFichaFAQHtml(f,model,null,'p1->p2').includes('propuesto'));
 const p=puentes.porFicha.get(f.id);
 for(const v of ['orientacion','apoyos']) {
   const els=elementosPuentes(model,fichas,puentes,f.id,v);
   assert(els.filter(x=>x.group==='nodes').length>0);
   assert(els.filter(x=>x.group==='edges').every(x=>x.data.source===`puente:ficha:${f.id}`));
   assert(!els.some(x=>x.data.tipo==='contiene'));
   assert(inspectorPuentesHtml(model,fichas,puentes,f.id,v));
 }
}
const elements=elementosRedFichas(fichas,red);
assert.equal(elements.filter(e=>e.group==='nodes').length,7);
assert.equal(elements.filter(e=>e.group==='edges').length,8);
const ids=new Set(elements.filter(e=>e.group==='nodes').map(e=>e.data.id));
assert(elements.filter(e=>e.group==='edges').every(e=>ids.has(e.data.source)&&ids.has(e.data.target)&&e.data.tipo==='relacion_entre_fichas'));
const first=red.relaciones[0];
assert(inspectorRedFichasHtml(fichas,red,null,first.id).includes('data-arch-card'));
assert(inspectorRedFichasHtml(fichas,red,'faq.lab.felicidad').includes('Abrir explicación'));
assert(inspectorRedFichasHtml(fichas,red).includes('data-arch-card="faq.lab.virtudes"'));
const variant=fn=>{ const v=structuredClone(resource);fn(v);return v;};
const build=v=>construirAmpliacionFichas(model,fichasBase,puentesBase,v);
assert.throws(()=>build(variant(v=>v.fuente.revision='otra')),/revisión/);
assert.throws(()=>build(variant(v=>v.fichas[0].pasos.pop())),/seis pasos/);
assert.throws(()=>build(variant(v=>v.fichas[0].pasos[0].sub_id='inventado')),/paso/);
assert.throws(()=>build(variant(v=>v.fichas[0].apoyos[0].sub_id='inventado')),/pasaje/);
assert.throws(()=>build(variant(v=>v.fichas[0].contextos.unidades[0].id='idea_bien')),/pasaje|unidad/);
assert.throws(()=>build(variant(v=>v.red.relaciones[0].hacia='desconocido')),/arista/);
assert.throws(()=>build(variant(v=>v.red.relaciones[1].id=v.red.relaciones[0].id)),/arista/);
const x=build(variant(v=>v.fichas[0].pasos[0].titulo='<img src=x onerror=alert(1)>'));
assert(!inspectorFichaFAQHtml(x.fichas.porId.get('faq.lab.felicidad'),model,'p1',null).includes('<img'));
const y=build(variant(v=>v.red.relaciones[0].nombre='<svg onload=alert(1)>'));
assert(!inspectorRedFichasHtml(y.fichas,y.red,null,'red:r01').includes('<svg'));
assert.equal(JSON.stringify(fuente),original,'el contenido de la exportación no debe mutar');
console.log('N1-U.7 OK: 7 fichas (4 nuevas), 4×6 pasos, 4×5 transiciones, 8 aristas curatoriales; 7 puentes; integridad, revisión, HTML seguro y solo lectura.');
